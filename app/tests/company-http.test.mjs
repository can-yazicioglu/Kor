// Real local HTTP + DOM integration. This is not visual browser verification.
// The Python harness owns server startup, port selection and teardown.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { parseHTML } from 'linkedom';
const base = process.env.SENTINEL_TEST_URL;
const tuned = process.argv.includes('--tuned');
if (!base) { console.log('Set SENTINEL_TEST_URL to a test-owned loopback server to run HTTP DOM checks.'); process.exit(0); }
const baseUrl = new URL(base);
assert.equal(baseUrl.protocol, 'http:');
assert.ok(['127.0.0.1', 'localhost'].includes(baseUrl.hostname));
const { window, document } = parseHTML(await readFile(new URL('../company.html', import.meta.url), 'utf8'));
globalThis.window = window; globalThis.document = document;
const $ = id => document.getElementById(id);
Object.defineProperty($('login-context'), 'value', { value: 'familiar', writable: true });
const nativeFetch = globalThis.fetch;
const nativeInterval = globalThis.setInterval;
globalThis.setInterval = (callback, ms) => { const timer = nativeInterval(callback, ms); timer.unref(); return timer; };
const calls = [], responses = [];
let failNext = false;
globalThis.fetch = async (url, options) => {
  assert.match(url, /^\.\/api\/demo\/(start|attempt|simulate|mfa|reset|feedback|status)$/);
  if (failNext) { failNext = false; throw new Error('Test network failure'); }
  assert.equal(options.method, 'POST');
  assert.equal(options.credentials, 'omit');
  const response = await nativeFetch(new URL(url, baseUrl), {
    ...options, headers: { ...options.headers, Origin: baseUrl.origin },
  });
  calls.push({ route: url, status: response.status });
  responses.push({ route: url, status: response.status, value: await response.clone().json() });
  return response;
};
const waitFor = async (predicate, note = 'operation') => {
  for (let i = 0; i < 600; i++) {
    if (predicate()) return;
    await new Promise(resolve => setTimeout(resolve, 10));
  }
  assert.fail('Real HTTP DOM ' + note + ' did not finish. Last route/status: ' + JSON.stringify(calls.at(-1)));
};
const dispatch = (id, type = 'click') => $(id).dispatchEvent(new window.Event(type, { bubbles: true, cancelable: true }));
const ready = () => waitFor(() => !$('sign-in').disabled);
const last = () => responses.at(-1)?.value;
const login = async password => {
  $('username').value = 'demo'; $('password').value = password ?? 'VelaDemo!42';
  dispatch('login-form', 'submit');
  assert.equal($('password').value, '');
  await ready();
  assert.equal(calls.at(-1).status, 200);
  assert.equal($('risk-score').textContent, last().latest.score === null ? '—' : String(last().latest.score));
};
const reset = async () => { dispatch('reset-company'); await ready(); assert.equal($('event-total').textContent, '0 EVENTS'); };
let checks = 0;
await import('../company.js');
await ready();
assert.equal(calls[0].route, './api/demo/start'); assert.equal(calls[0].status, 200);
assert.equal($('workspace-panel').hidden, true);
assert.equal(last().snapshot.insights.lifecycle.events, 0);
assert.match($('lifetime-inventory').textContent, /Event records/);
const asset = await nativeFetch(new URL('/insights.js', baseUrl));
assert.equal(asset.status, 200); assert.match(asset.headers.get('Content-Type'), /javascript/);
checks++;
await login();
assert.equal($('workspace-panel').hidden, !last().allowed_access);
assert.equal($('mfa-panel').hidden, !last().mfa_required);
assert.match($('verification-status').textContent, /Password verified by local server/);
if (tuned) {
  assert.match(last().latest.model_version, /^els-tuned-v2-/);
  assert.equal(last().latest.sequence_policy_version, 'els-contextual-shadow-v3');
  assert.equal(last().allowed_access, true, 'The test-injected candidate should allow this familiar synthetic sign-in');
  assert.equal(last().mfa_required, false);
}
assert.equal($('history-rows').children.length, 3);
assert.match($('decision-summary').textContent, /First retained event/);
checks++;
const beforeRefresh = last();
dispatch('refresh-insights'); await ready();
assert.equal(calls.at(-1).route, './api/demo/status');
assert.equal(last().total, beforeRefresh.total);
assert.deepEqual(last().insights.decision_delta, beforeRefresh.insights.decision_delta);
assert.ok(last().remaining_ms <= beforeRefresh.remaining_ms);
assert.equal($('mfa-panel').hidden, !last().mfa_required);
checks++;
await reset(); dispatch('run-brute'); await ready();
assert.equal(calls.at(-1).status, 200);
assert.equal($('event-total').textContent, '20 EVENTS'); assert.equal($('attempt-count').textContent, '20');
assert.equal($('workspace-panel').hidden, true);
assert.match($('history-summary').textContent, /30s is the shortest tested/);
assert.match($('history-rows').textContent, /Repeated account failures/);
checks++;
await login();
assert.equal(last().mfa_required, true);
assert.equal($('mfa-panel').hidden, false);
assert.equal($('workspace-panel').hidden, true);
checks++;
$('mfa-code').value = '000000'; dispatch('mfa-form', 'submit');
assert.equal($('mfa-code').value, ''); await ready();
assert.equal(calls.at(-1).status, 200);
assert.equal(last().allowed_access, false);
assert.equal($('workspace-panel').hidden, true);
checks++;
$('mfa-code').value = '123456'; dispatch('mfa-form', 'submit'); await ready();
assert.equal(calls.at(-1).status, 200);
assert.equal(last().allowed_access, true);
assert.equal($('workspace-panel').hidden, false);
assert.match($('verification-status').textContent, /MFA verified by local server/);
assert.match($('decision-changes').textContent, /Password verified → MFA verified/);
assert.equal(last().insights.decision_delta.current_action, 'review');
checks++;
failNext = true; dispatch('refresh-insights'); await ready();
assert.equal($('workspace-panel').hidden, true);
assert.equal($('history-rows').children.length, 0);
assert.equal($('lifetime-inventory').children.length, 0);
assert.match($('history-summary').textContent, /unavailable/);
checks++;
await reset(); dispatch('run-distributed'); await ready();
assert.equal(calls.at(-1).status, 200); assert.equal($('event-total').textContent, '12 EVENTS');
assert.equal($('source-count').textContent, '12');
checks++;
dispatch('feedback-suspicious'); await ready();
assert.equal(calls.at(-1).route, './api/demo/feedback'); assert.equal(calls.at(-1).status, 200);
assert.match($('feedback-status').textContent, /saved/);
assert.equal($('workspace-panel').hidden, true);
checks++;
await reset(); await login('password');
assert.match($('password-match').textContent, /Exact reference match/);
assert.equal($('credential-strength').textContent, 'Weakness signal');
assert.equal(last().latest.credential_risk.numeric_bonus, 0);
assert.match($('password-check-note').textContent, /no fixed score is added/);
assert.equal($('workspace-panel').hidden, true);
checks++;
await reset(); $('login-context').value = 'cold_start'; await login();
assert.equal($('risk-score').textContent, '—');
assert.equal($('workspace-panel').hidden, true); assert.equal($('mfa-panel').hidden, true);
assert.match($('data-quality-note').textContent, /Missing context/);
checks++;
await reset();
assert.equal($('session-peak').textContent, '—'); assert.equal($('password').value, '');
assert.equal($('history-rows').children.length, 0);
assert.equal($('decision-changes').children.length, 0);
assert.equal(last().snapshot.insights.lifecycle.events, 0);
await login();
assert.equal($('history-rows').children.length, 3);
const beforeLeave = calls.length;
window.dispatchEvent(new window.Event('pagehide'));
await waitFor(() => calls.length > beforeLeave, 'pagehide cleanup');
assert.equal(calls.at(-1).route, './api/demo/reset');
assert.equal($('workspace-panel').hidden, true);
assert.equal($('sign-in').disabled, true);
assert.equal($('lifetime-inventory').children.length, 0);
assert.equal($('history-rows').children.length, 0);
checks++;
console.log(checks + ' real HTTP company DOM checks passed (no visual browser verification).');
